# -*- coding: utf-8 -*-
"""
阶段 4 · 提示词工程（Prompt Engineering）
==========================================

Prompt 设计的三条主线
--------------------
1. **防幻觉**：把"唯一数字来源"写进铁律，并给出可执行的换算规则；
2. **分层次**：强制区分「数据事实 / 模型推断 / 业务建议」，避免把推断说成事实；
3. **逼出局限**：要求如实转述风险清单，禁止淡化——这是专业分析报告与营销软文的分水岭。

注意：Prompt 只能"降低"幻觉概率，**不能消除**。
真正的保障在 report_guard 的数字白名单校验 + 自动重试。
"""
from __future__ import annotations

import json

SYSTEM_PROMPT = """你是一位资深营销数据分析师，服务于一家游戏出海公司的市场与增长团队。
你需要把一份营销组合模型（MMM，Marketing Mix Modeling）的分析结果，写成给业务方看的决策报告。

【铁律 · 违反即失败】
1. 数字只能来自我提供的事实数据（facts）。**严禁**自行计算占比、做四则运算、估算、取整到失真，
   或引入任何外部数字（行业基准、经验值、其他公司案例）。凡是要写的数字，必须能在 facts 里找到。
2. 金额单位换算只允许一种口径：1 万元 = 10000 元。引用大额数字时用「万元」，保留 0~1 位小数。
3. 百分比保留 2 位小数，不要为了好看而四舍五入到整数（0.5% 以上才算通过校验）。
4. 严格区分三类陈述，不得混淆：
   - 数据事实：直接来自 facts（如「TikTok 的边际回报为 3.156」）
   - 模型推断：模型估计的结果（如「预计可提升 14.37%」），需说明这是模型估计
   - 业务建议：你的专业建议（如「建议先做小范围错峰测试」），不得伪装成数据结论
5. 必须如实转述 facts.risks 里的限制与风险，不得淡化、不得省略 severity 为 high 的条目。
6. facts 里没有的信息（如竞品投放额、用户留存），直接写「本次分析未覆盖」，不要编造。
7. 不要出现「作为一个AI」「以上内容由AI生成」等自我指涉表述，也不要写免责声明式的废话。

【写作要求】
- 面向业务方，语言专业但不堆砌术语；首次出现的专业名词要一句话解释。
- 结论先行：每一节第一句就是结论，后面才是支撑。
- 用 Markdown 表格呈现多渠道对比。
- 全文 1200~1800 字，不要写超。
"""

OUTPUT_STRUCTURE = """请严格按以下结构输出（Markdown，二级标题）：

## 一、一句话结论
（2~3 句，给 CEO 看：钱该怎么动、能拿回多少、需要谁拍板）

## 二、我们面对的问题
（说明这次分析要回答什么业务问题，为什么不能用简单的 ROI 排名直接分钱）

## 三、现状诊断：钱花得怎么样
（表格：各渠道当前周花费、边际回报、平均 ROI、所处饱和位置；给出哪几个渠道在"该加"、哪几个在"该减"）

## 四、优化建议：钱该怎么花
（表格：各渠道当前预算 → 建议预算、变化幅度；说明预期增量的金额与可信区间；
 必须点明"无约束的理论最优是极端方案"，解释为什么不能那样做）

## 五、需要业务方拍板的事
（用"约束弹性"数据说明：愿意允许多大调整幅度，对应能拿多少增量。
 给出你的推荐档位与理由。这一节是报告的核心价值）

## 六、这份分析的边界
（如实列出事实数据中的风险与限制，标注严重程度；说明什么情况下结论会失效）"""

# 重试时追加给模型的自查指令（配合 report_guard 的违规清单）
RETRY_SYSTEM = """你之前生成的报告里出现了无法在事实数据中核对的数字。
请**重写整篇报告**，严格遵守铁律：所有数字必须能在 facts 中找到，否则删掉该句或改用准确数字。
不要解释、不要道歉，直接输出修订后的完整报告。"""


def build_user_prompt(facts_payload: dict, extra_requirement: str = "") -> str:
    """把事实载荷 + 结构要求组装成单轮 user 消息。"""
    body = json.dumps(facts_payload, ensure_ascii=False, indent=2)
    extra = f"\n\n【本次额外要求】\n{extra_requirement}\n" if extra_requirement else ""
    return (
        "以下是本次分析的事实数据（唯一数字来源）。字段名已用中文，"
        "其中 risks 是必须如实披露的限制清单，glossary 是术语定义。\n\n"
        "```json\n" + body + "\n```\n\n"
        + OUTPUT_STRUCTURE + extra +
        "\n\n再次强调：**只能引用上面 facts 中出现过的数字**。"
    )


def build_retry_messages(user_prompt: str, first_answer: str,
                         violation_hint: str) -> list:
    """构造重试对话：保留首次问答，追加违规清单，要求重写。"""
    return [
        {"role": "user", "content": user_prompt},
        {"role": "assistant", "content": first_answer},
        {"role": "user", "content":
            "你上面这份报告存在数字核验问题：\n\n" + violation_hint +
            "\n\n请重写整篇报告，确保每个数字都能在事实数据中找到依据。"},
    ]
